#!/usr/bin/env bun
// Conservative selection for the exact rebased candidate. Release/nightly stays complete.
import { spawnSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readFileSync, rmSync, symlinkSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SHA = /^[0-9a-f]{40}$/;
const CODE = /\.[cm]?[jt]sx?$/;
const GLOBAL = /^(?:package\.json|bun\.lockb?|bunfig\.toml|tsconfig[^/]*\.json|vite[^/]*\.[cm]?[jt]s|slipjay\.json|tests\/quarantine\.json|scripts\/)/;
const HARMLESS = /^(?:docs\/|(?:README|CHANGELOG|GLOSSARY|AGENTS)\.md$|\.gitignore$)/;
const validPath = (file: string) => !!file && !path.isAbsolute(file) && !file.split("/").includes("..") && !/[\n\r\t]/.test(file);
// Other filesystem reads consume disposable state generated by the tests.
export const FIXTURE_READERS = { "tests/runner/fixtures/pipeline/": ["tests/runner/runner-pipeline-fixtures.test.ts"] };
// Tests that run a source entry in another process (the CLI, a launcher entry or the installed package), out of
// the import graph. A test whose child imports only modules the test itself imports (runner-queue's) needs no entry.
export const PROCESS_TESTS = [
  "integration/cli", "integration/installed-package", "integration/landed-record",
  "landing/landing-outcome", "landing/landing-primary-checkout-move", "landing/landing-primary-checkout-preserve", "landing/repair-claim-cli", "landing/repair-workspace",
  "landing/submission-handoff-cli", "landing/submission-source-export",
  "runner/command-artifact",
  "workspace/bun-store-damage", "workspace/cutover", "workspace/workspace-attempts", "workspace/workspace-housekeeping-cleanup",
  "workspace/workspace-lifecycle-convergence-landing", "workspace/workspace-lifecycle-convergence-issue",
  "workspace/workspace-retention-plan-inventory", "workspace/workspace-retention-plan-landing",
  "workspace/workspace-spare-dependencies-allocation",
  "workspace/workspace-sweep-guards",
].map((name) => `tests/${name}.test.ts`);
// package.json is the single inventory for both complete and landing runtime runs.
export function runtimeTestFiles(command: string): string[] {
  const [executable, subcommand, ...files] = command.trim().split(/\s+/);
  if (executable !== "bun" || subcommand !== "test" || !files.length || files.some((file) => !validPath(file) || !/^scripts\/[A-Za-z0-9._-]+\.test\.ts$/.test(file))) throw new Error("test:runtimes must explicitly list Bun test files");
  return files;
}
export const RUNTIME_TESTS = runtimeTestFiles((JSON.parse(readFileSync(path.join(ROOT, "package.json"), "utf8")) as { scripts: Record<string, string> }).scripts["test:runtimes"] ?? "");
export type LandingTests = { kind: "complete"; reason: string } | { kind: "related"; files: string[]; reasons: string[] } | { kind: "none" };
export function selectLandingTests(changed: string[], deleted: string[]): LandingTests {
  if (deleted.length) return { kind: "complete", reason: `${deleted[0]} was deleted; dependency edges are unavailable` };
  const files = new Set<string>();
  const reasons: string[] = [];
  for (const file of changed) {
    if (!validPath(file) || GLOBAL.test(file)) return { kind: "complete", reason: `${file} can affect every test` };
    const fixture = Object.entries(FIXTURE_READERS).find(([prefix]) => file.startsWith(prefix));
    if (fixture) {
      fixture[1].forEach((test) => files.add(test));
      reasons.push(`${file}: runtime fixture reader ${fixture[1].join(", ")}`);
    } else if (CODE.test(file) && /^(src|tests)\//.test(file)) {
      files.add(file);
      reasons.push(`${file}: import graph`);
    } else if (!HARMLESS.test(file)) return { kind: "complete", reason: `${file} has no known dependency mapping` };
  }
  if (changed.some((file) => file.startsWith("src/"))) {
    PROCESS_TESTS.forEach((test) => files.add(test));
    reasons.push("src/** changed: source CLI/subprocess callers");
  }
  return files.size ? { kind: "related", files: [...files].sort(), reasons } : { kind: "none" };
}
/** A release bump: package.json differs only in its `version`, which no test reads. */
export function versionOnlyChange(before: string, after: string): boolean {
  try {
    const strip = (text: string) => { const parsed = JSON.parse(text) as Record<string, unknown>; delete parsed.version; return JSON.stringify(parsed); };
    return strip(before) === strip(after);
  } catch { return false; }
}
export type JjQuery = (args: string[]) => string;
const jj: JjQuery = (args) => {
  const result = spawnSync("jj", ["--color=never", ...args], { cwd: ROOT, encoding: "utf8", maxBuffer: 16 * 1024 * 1024, timeout: 30_000 });
  if (result.status !== 0) throw new Error(`JJ query failed: ${result.stderr || result.error}`);
  return result.stdout;
};
function facts(query: JjQuery, revision: string) {
  const [candidate, parent, conflict, empty] = query(["log", "--no-graph", "-r", revision, "-T", 'commit_id ++ "\\n" ++ parents.map(|p| p.commit_id()).join(" ") ++ "\\n" ++ conflict ++ "\\n" ++ empty']).trim().split("\n");
  if (!candidate || !SHA.test(candidate) || !parent || !SHA.test(parent) || conflict !== "false" || !["true", "false"].includes(empty ?? "")) throw new Error("Candidate must be conflict-free with exactly one parent");
  return { candidate, parent, empty };
}
export function candidateChanges(query: JjQuery = jj, integrationBranch = (JSON.parse(readFileSync(path.join(ROOT, "slipjay.json"), "utf8")) as { integrationBranch: string }).integrationBranch) {
  if (!/^[A-Za-z0-9._/-]+$/.test(integrationBranch)) throw new Error("Invalid integration branch");
  const working = facts(query, "@"); // Snapshot before immutable reads.
  const integration = query(["log", "--ignore-working-copy", "--no-graph", "-r", integrationBranch, "-T", "commit_id"]).trim();
  if (!SHA.test(integration)) throw new Error("Ambiguous integration bookmark");
  const identity = working.empty === "true" && working.parent !== integration ? facts(query, working.parent) : working;
  if (identity.parent !== integration) throw new Error("Candidate is not rebased onto the single integration parent");
  const tracked = (revision: string) => {
    const files = query(["file", "list", "--ignore-working-copy", "-r", revision]).trimEnd().split("\n").filter(Boolean);
    if (files.some((file) => !validPath(file))) throw new Error("Unsupported tracked path");
    return files;
  };
  const current = new Set(tracked(identity.candidate));
  const deleted = tracked(identity.parent).filter((file) => !current.has(file));
  const show = (revision: string) => query(["file", "show", "--ignore-working-copy", "-r", revision, "package.json"]);
  const changed = [...new Set([...query(["diff", "--ignore-working-copy", "--from", identity.parent, "--to", identity.candidate, "-T", 'json(path) ++ "\\n"']).trim().split("\n").filter(Boolean).map((line) => JSON.parse(line) as string), ...deleted])]
    .filter((file) => file !== "package.json" || deleted.includes(file) || !current.has(file) || !versionOnlyChange(show(identity.parent), show(identity.candidate)));
  if (changed.some((file) => !validPath(file))) throw new Error("Unsupported changed path");
  const assertUnchanged = () => {
    const after = facts(query, "@");
    const parent = query(["log", "--ignore-working-copy", "--no-graph", "-r", integrationBranch, "-T", "commit_id"]).trim();
    if (after.candidate !== working.candidate || after.parent !== working.parent || parent !== integration) throw new Error("Candidate or integration parent changed during verification");
  };
  assertUnchanged();
  return { ...identity, changed, deleted, assertUnchanged };
}
export function planCandidate(read: () => ReturnType<typeof candidateChanges>): LandingTests {
  try { const snapshot = read(); return selectLandingTests(snapshot.changed, snapshot.deleted); }
  catch (error) { return { kind: "complete", reason: `candidate unreadable or ambiguous: ${String(error)}` }; }
}
export type Quarantine = { file: string; issue: number; reason: string };
export function readQuarantine(text: string): Quarantine[] {
  const entries: unknown = JSON.parse(text);
  if (!Array.isArray(entries) || entries.some((entry) => !entry || typeof entry.file !== "string" || !validPath(entry.file) || !/^(tests|scripts)\/.*\.test\.ts$/.test(entry.file) || !Number.isSafeInteger(entry.issue) || entry.issue <= 0 || typeof entry.reason !== "string" || !entry.reason.trim())) throw new Error("Invalid quarantine registry; each test needs an open Issue number and reason");
  return entries as Quarantine[];
}
export function landingCommands(plan: LandingTests, quarantine: Quarantine[], reportDir?: string) {
  const excluded = new Set(quarantine.map((entry) => entry.file));
  const vitest = plan.kind === "complete" ? ["bunx", "vp", "test", "run"] : plan.kind === "related" ? ["bunx", "vp", "test", "related", ...plan.files, "--run"] : undefined;
  type Report = { format: "vitest-json" | "bun-junit"; path: string; suite: string; cwd: string };
  const commands: { suite: string; command: string[]; report?: Report }[] = [];
  if (vitest) {
    vitest.push("--passWithNoTests", ...[...excluded].flatMap((file) => ["--exclude", file]));
    if (reportDir) vitest.push("--reporter=default", "--reporter=json", `--outputFile.json=${path.join(reportDir, "vitest.json")}`);
    commands.push({ suite: "vitest", command: vitest, ...(reportDir ? { report: { format: "vitest-json" as const, path: "vitest.json", suite: "vitest", cwd: "." } } : {}) });
  }
  const runtimes = RUNTIME_TESTS.filter((file) => !excluded.has(file));
  if (runtimes.length) commands.push({ suite: "runtimes", command: ["bun", "test", ...runtimes, ...(reportDir ? ["--reporter=junit", `--reporter-outfile=${path.join(reportDir, "bun-junit.xml")}`] : [])], ...(reportDir ? { report: { format: "bun-junit" as const, path: "bun-junit.xml", suite: "runtimes", cwd: "." } } : {}) });
  return commands;
}
if (import.meta.main) {
  if (process.argv.includes("--replay")) {
    // Rehydrate immutable JJ trees as disposable graph inputs under this workspace.
    // They have no VCS metadata, and no historical test body is executed.
    const { createVitest } = await import("vite-plus/test/node");
    mkdirSync(path.join(ROOT, ".build"), { recursive: true });
    const scratch = mkdtempSync(path.join(ROOT, ".build/landing-replay-"));
    try {
      const commits = jj(["log", "--ignore-working-copy", "--no-graph", "-r", "ancestors(main, 30)", "-T", 'commit_id ++ "\\n"']).trim().split("\n");
      console.log("commit | selected/complete (includes runtime files) | reason");
      let half = 0;
      let previous = new Set<string>();
      // Oldest first allows updating only changed files between graph snapshots.
      for (const commit of commits.toReversed()) {
        const identity = facts(jj, commit);
        const parent = jj(["file", "list", "--ignore-working-copy", "-r", identity.parent]).trim().split("\n");
        const current = new Set(jj(["file", "list", "--ignore-working-copy", "-r", commit]).trim().split("\n"));
        const show = (revision: string) => jj(["file", "show", "--ignore-working-copy", "-r", revision, "package.json"]);
        const changed = jj(["diff", "--ignore-working-copy", "--from", identity.parent, "--to", commit, "-T", 'json(path) ++ "\\n"']).trim().split("\n").filter(Boolean).map((line) => JSON.parse(line) as string)
          .filter((file) => file !== "package.json" || !current.has(file) || !parent.includes(file) || !versionOnlyChange(show(identity.parent), show(commit)));
        const plan = selectLandingTests(changed, parent.filter((file) => !current.has(file)));
        for (const file of previous) if (!current.has(file)) rmSync(path.join(scratch, file), { force: true });
        for (const file of current) {
          if (!validPath(file)) throw new Error("Unsupported replay path");
          if (!previous.has(file) || changed.includes(file)) {
            mkdirSync(path.dirname(path.join(scratch, file)), { recursive: true });
            writeFileSync(path.join(scratch, file), jj(["file", "show", "--ignore-working-copy", "-r", commit, file]));
          }
        }
        if (!previous.size) symlinkSync(path.join(ROOT, "node_modules"), path.join(scratch, "node_modules"), "dir");
        previous = current;
        const ctx = await createVitest({ root: scratch, watch: false, run: true, related: plan.kind === "related" ? plan.files.map((file) => path.join(scratch, file)) : undefined });
        try {
          const all = await ctx.globTestSpecifications();
          const count = (plan.kind === "none" ? 0 : plan.kind === "complete" ? all.length : (await ctx.getRelevantTestSpecifications()).length) + RUNTIME_TESTS.length;
          const total = all.length + RUNTIME_TESTS.length;
          if (count <= total / 2) half++;
          console.log(`${commit.slice(0, 12)} | ${count}/${total} | ${plan.kind === "complete" ? plan.reason : plan.kind}`);
        } finally { await ctx.close(); }
      }
      console.log(`At most half: ${half}/${commits.length}; historical graphs and parent diffs; current runtime lane (${RUNTIME_TESTS.length} files). Main pinned at ${commits[0]}.`);
    } finally { rmSync(scratch, { recursive: true, force: true }); }
  } else {
    // The nightly audit (`--audit`) runs the complete suite, quarantined tests included, with the same reports.
    const audit = process.argv.includes("--audit");
    let snapshot: ReturnType<typeof candidateChanges> | undefined;
    const plan: LandingTests = audit ? { kind: "complete", reason: "audit" } : planCandidate(() => (snapshot = candidateChanges()));
    console.log(JSON.stringify({ candidate: snapshot?.candidate, parent: snapshot?.parent, changed: snapshot?.changed, selection: plan }, null, 2));
    const quarantine = audit ? [] : readQuarantine(readFileSync(path.join(ROOT, "tests/quarantine.json"), "utf8"));
    console.log("Landing quarantine exclusions:", JSON.stringify(quarantine));
    let reportDir = process.env.SLIPJAY_TEST_REPORT_DIR ? path.resolve(process.env.SLIPJAY_TEST_REPORT_DIR) : undefined;
    if (reportDir) try { mkdirSync(reportDir, { recursive: true }); } catch (error) { console.warn("Reports unavailable:", error); reportDir = undefined; }
    if (reportDir) try { writeFileSync(path.join(reportDir, "slipjay-test-reports.json"), JSON.stringify({ version: 1, reports: landingCommands(plan, quarantine, reportDir).flatMap((entry) => entry.report ? [entry.report] : []) })); } catch (error) { console.warn("Report manifest unavailable:", error); reportDir = undefined; }
    const commands = landingCommands(plan, quarantine, reportDir);
    let exit = 0;
    for (const { command } of commands) {
      console.log(`$ ${command.join(" ")}`);
      const result = spawnSync(command[0]!, command.slice(1), { cwd: ROOT, stdio: "inherit" }).status ?? 1;
      exit ||= result;
    }
    try { snapshot?.assertUnchanged(); } catch (error) { console.error(error); exit = 1; }
    process.exitCode = exit;
  }
}
