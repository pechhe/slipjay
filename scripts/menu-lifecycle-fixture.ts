import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { TERMINAL_EVENT_TYPES } from "../src/lib/runner-contract.ts";
import type { CompletedRelease, OperationEvent } from "../src/lib/runner-contract.ts";
import { openOperationLog } from "../src/lib/runner-log.ts";
import type { WatchEnvelope } from "../src/lib/runner-watch.ts";

const at = "2026-10-14T00:00:00.000Z";
export const fixtureRelease = {
  ok: true, status: "released", integrationBranch: "main", releaseBranch: "release", remote: "origin",
  base: "previous-release", candidate: "approved-candidate", merge: "release-merge", commits: 1,
  migrationArtifacts: [], nonAdditiveMigrations: [], paths: [], checks: [], verification: {}, releasedAt: at,
} satisfies CompletedRelease;

export function swiftRunnerContract(): string {
  return `// Generated by bun scripts/menu-lifecycle-fixture.ts; checked by tests/menu-notification-fixture.test.ts.\nimport Foundation\n\nenum RunnerContract {\n    static let terminalEventTypes: Set<String> = [${TERMINAL_EVENT_TYPES.map((type) => JSON.stringify(type)).join(", ")}]\n}\n`;
}

/** Real ledger events and snapshots; only wall-clock fields are normalized. */
export function menuLifecycleFixture(): string {
  const log = openOperationLog(":memory:");
  const envelopes: WatchEnvelope[] = [];
  const terminalFacts = {
    landed: { type: "landed", base: "base", commitId: "landed-commit", branch: "main", remote: "origin" },
    released: { type: "released", result: fixtureRelease },
    deployed: { type: "deployed", record: { environment: "production", commitId: "release-merge", previous: null, changes: [], projects: [] } },
    reset: { type: "reset", target: "database", source: "source" },
    failed: { type: "failed", stage: "verifying", reason: "fixture failure" },
    declined: { type: "declined", reason: "migration", paths: ["migration.sql"] },
    superseded: { type: "superseded", by: "new-submission" },
    cancelled: { type: "cancelled", reason: "fixture cancellation" },
  } satisfies Record<(typeof TERMINAL_EVENT_TYPES)[number], OperationEvent>;
  try {
    envelopes.push({ version: 1, type: "snapshot", snapshot: log.snapshot("fixture-runner", new Date(at)) });
    envelopes.push({ version: 1, type: "connection", state: "connected", cursor: 0 });
    let cursor = 0;
    function flush() {
      for (const event of log.events({ afterSeq: cursor })) {
        envelopes.push({ version: 1, type: "event", event }); cursor = event.seq;
      }
    }
    for (const type of TERMINAL_EVENT_TYPES) {
      const id = type === "released" ? "release-1" : `terminal-${type}`;
      const submission: OperationEvent = type === "released"
        ? { type: "submitted", kind: "release", repo: "fixture/repo", commitId: fixtureRelease.candidate, migrationsReady: false, submittedBy: "owner" }
        : type === "deployed"
          ? { type: "submitted", kind: "deploy", environment: "production", repo: "fixture/repo", commitId: "release-merge", submittedBy: "owner" }
          : type === "reset"
            ? { type: "submitted", kind: "reset", repo: "fixture/repo", commitId: "source", submittedBy: "owner" }
            : { type: "submitted", repo: "fixture/repo", commitId: "source", changeId: id, bookmark: `slipjay/changes/${id}`, submittedBy: "owner" };
      log.append(id, submission);
      log.append(id, { type: "stage", stage: type === "deployed" ? "deploying" : type === "reset" ? "resetting" : "verifying" });
      flush();
      if (type === "released") envelopes.push({ version: 1, type: "snapshot", snapshot: log.snapshot("fixture-runner", new Date(at)) });
      log.append(id, terminalFacts[type]); flush();
    }
    envelopes.push({ version: 1, type: "heartbeat", at, seq: cursor });
    // The running release has no completed same-kind stage samples, so date
    // normalization does not alter its timing assessment.
    return envelopes.map((envelope) => JSON.stringify(envelope, (key, value: unknown) =>
      ["at", "observedAt", "submittedAt", "stageStartedAt", "finishedAt"].includes(key) && typeof value === "string" ? at : value)).join("\n") + "\n";
  } finally { log.close(); }
}

if (import.meta.main) {
  await writeFile(fileURLToPath(new URL("../macos/fixtures/lifecycle.jsonl", import.meta.url)), menuLifecycleFixture());
  await writeFile(fileURLToPath(new URL("../macos/RunnerContract.generated.swift", import.meta.url)), swiftRunnerContract());
}
